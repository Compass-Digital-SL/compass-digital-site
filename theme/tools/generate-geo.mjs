// Dev-only generator for the "Where we work" map outlines.
//
//   npm run geo        (from theme/)
//
// Reads Natural Earth 50m country polygons (bundled in the world-atlas dev
// dependency), drops Antarctica, simplifies with mapshaper to keep the payload
// small, rounds coordinates, and writes a committed ES module the front end
// imports lazily: assets/src/js/map/geo-50m.js.
//
// The output is committed so the front-end build never needs these dev tools.
// Re-run this only when the source data or simplification changes.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import mapshaper from "mapshaper";

const __dirname = dirname(fileURLToPath(import.meta.url));
const THEME = resolve(__dirname, "..");
const SRC = resolve(THEME, "node_modules/world-atlas/countries-50m.json");
const OUT = resolve(THEME, "assets/src/js/map/geo-50m.js");

// Simplification: lower = smaller + blockier. 12% keeps Sri Lanka / UAE / Japan
// readable at the zoomed scale while staying well under the payload budget.
const SIMPLIFY = "12%";
// Coordinate rounding (decimal places). 2dp ≈ ~1km — plenty once simplified.
const PRECISION = 2;

// Bounding boxes we fit the camera to, per country name (Natural Earth naming).
// Raw geometry bbox is used for everything else. These override countries whose
// far-flung territories (Alaska, Hawaii, overseas regions) would otherwise make
// the fit zoom way out. Format: [west, south, east, north].
const BBOX_OVERRIDES = {
  "United States of America": [-124.8, 24.4, -66.9, 49.4], // lower 48
  Canada: [-141.0, 41.7, -52.6, 70.0],
  Russia: [19.6, 41.2, 180.0, 77.0],
  France: [-5.2, 41.3, 9.6, 51.1], // metropolitan France
  Australia: [112.9, -43.7, 153.7, -10.0], // mainland + Tasmania
  "United Kingdom": [-8.7, 49.9, 1.8, 59.0],
  Norway: [4.5, 57.9, 31.1, 71.2], // mainland (drop Svalbard)
  "New Zealand": [166.3, -47.3, 178.6, -34.4],
  Netherlands: [3.3, 50.7, 7.3, 53.6], // European Netherlands
  Chile: [-75.7, -55.9, -66.4, -17.5],
  Portugal: [-9.6, 36.9, -6.2, 42.2], // mainland (drop Azores/Madeira)
  Spain: [-9.4, 35.9, 4.4, 43.9], // peninsula + Balearics
  Ecuador: [-81.1, -5.0, -75.2, 1.5], // mainland (drop Galapagos)
};

function round(n) {
  return Number(n.toFixed(PRECISION));
}

function roundRing(ring) {
  const out = [];
  let prev = null;
  for (const [x, y] of ring) {
    const p = [round(x), round(y)];
    // Drop consecutive duplicate points left by rounding.
    if (prev && p[0] === prev[0] && p[1] === prev[1]) continue;
    out.push(p);
    prev = p;
  }
  return out.length >= 4 ? out : null; // a polygon ring needs >= 4 points
}

// Normalise a GeoJSON geometry to an array of rings (outer rings only — holes
// are dropped; countries have none that matter at this scale), rounded.
function geomToRings(geom) {
  if (!geom) return [];
  const polys =
    geom.type === "Polygon"
      ? [geom.coordinates]
      : geom.type === "MultiPolygon"
        ? geom.coordinates
        : [];
  const rings = [];
  for (const poly of polys) {
    const r = roundRing(poly[0]); // outer ring
    if (r) rings.push(r);
  }
  return rings;
}

function bboxOf(rings) {
  let w = 180,
    s = 90,
    e = -180,
    n = -90;
  for (const ring of rings)
    for (const [x, y] of ring) {
      if (x < w) w = x;
      if (x > e) e = x;
      if (y < s) s = y;
      if (y > n) n = y;
    }
  return [round(w), round(s), round(e), round(n)];
}

const topo = readFileSync(SRC, "utf8");
const cmd = [
  "-i countries.json",
  `-simplify ${SIMPLIFY} keep-shapes`,
  "-o out.json format=geojson",
].join(" ");

const result = await new Promise((res, rej) =>
  mapshaper.applyCommands(cmd, { "countries.json": topo }, (err, out) => (err ? rej(err) : res(out)))
);
const outKey = Object.keys(result).find((k) => k.endsWith(".json"));
const raw = result[outKey];
const fc = JSON.parse(typeof raw === "string" ? raw : raw.toString("utf8"));

const countries = [];
for (const f of fc.features) {
  const name = f.properties && f.properties.name;
  if (!name || name === "Antarctica") continue;
  const rings = geomToRings(f.geometry);
  if (!rings.length) continue;
  const bbox = BBOX_OVERRIDES[name] || bboxOf(rings);
  countries.push({ n: name, b: bbox, r: rings });
}
countries.sort((a, b) => a.n.localeCompare(b.n));

const banner =
  "// GENERATED by tools/generate-geo.mjs — do not edit by hand.\n" +
  "// Natural Earth 50m country outlines (via world-atlas), Antarctica dropped,\n" +
  `// simplified ${SIMPLIFY}, coords rounded to ${PRECISION}dp. Keyed by Natural\n` +
  "// Earth country name. b = [west, south, east, north] fit box; r = outer rings.\n";
const body = `export const COUNTRIES = ${JSON.stringify(countries)};\n`;
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, banner + body);

const bytes = Buffer.byteLength(body, "utf8");
const gz = gzipSync(body).length;
console.log(`countries: ${countries.length}`);
console.log(`raw:  ${(bytes / 1024).toFixed(1)} KB`);
console.log(`gzip: ${(gz / 1024).toFixed(1)} KB  (budget ~150 KB)`);
console.log(`wrote ${OUT}`);
